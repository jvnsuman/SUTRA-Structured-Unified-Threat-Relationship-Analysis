"""
api/report_builder.py

Builds a case report from what is actually persisted and analysed for the
case: sources, network size, ranked key individuals with the reason each
was flagged, entities awaiting investigator review, detected patterns,
and the source documents behind each key individual.

Output formats: Markdown, CSV (entity table) and PDF (reportlab, BSD).
The PDF is the prosecutor-facing artefact from the project's personas:
a printable summary in which every claim names its source documents --
"explainable, not a risk score".

This is decision support for investigators. Nothing here predicts
anyone's future behaviour or scores an individual's likelihood of
offending; "key influencer" means network position within the case's
own evidence (see graph.build.rank_influencers).
"""

from __future__ import annotations

import csv
import io
from datetime import datetime, timezone

from sqlalchemy.orm import Session

from api.casegraph import build_case_graph
from db import repository as repo
from graph.analytics import detect_anomalies
from graph.build import rank_influencers
from schema.case import Case

DISCLAIMER = (
    "Generated by an automated analysis of the documents ingested for this case. Findings are leads for "
    "investigators to verify against the cited source documents; they are not evidence of guilt, and no "
    "individual is scored or predicted. Entities marked 'needs review' were merged on weaker evidence and "
    "should be confirmed before being relied upon."
)


def build_case_report_data(db: Session, case: Case) -> dict:
    graph, resolved, mentions = build_case_graph(db, case.id)
    sources = repo.get_document_summary_for_case(db, case.id)
    data = {
        "case": {"id": case.id, "title": case.title, "status": case.status.value, "opened_at": case.opened_at},
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "sources": sources,
        "counts": {}, "influencers": [], "review": [], "alerts": [], "entities": [], "overrides": [],
    }
    if graph is None:
        return data

    by_type: dict = {}
    for _, attrs in graph.nodes(data=True):
        by_type[attrs["entity_type"].lower()] = by_type.get(attrs["entity_type"].lower(), 0) + 1
    data["counts"] = {"entities": graph.number_of_nodes(), "relationships": graph.number_of_edges(),
                      "mentions": len(mentions), "by_type": by_type}

    for r in rank_influencers(graph, top_n=5):
        attrs = graph.nodes[r["node_id"]]
        docs = sorted(attrs.get("source_doc_ids", []))
        data["influencers"].append({
            "rank": r["rank"], "name": attrs["canonical_text"], "aliases": list(attrs.get("aliases", [])),
            "reason": r["reason"], "documents": docs, "needs_review": bool(attrs.get("needs_review")),
        })

    for e in resolved:
        entry = {"name": e.canonical_text, "type": e.entity_type.value.lower(),
                 "documents": sorted(e.source_doc_ids), "aliases": list(e.aliases),
                 "merge_confidence": round(e.merge_confidence, 2), "needs_review": e.needs_review,
                 "reasons": list(e.merge_reasons)}
        data["entities"].append(entry)
        if e.needs_review:
            data["review"].append(entry)

    docs = repo.get_documents_for_case(db, case.id)
    for f in detect_anomalies(graph, docs):
        data["alerts"].append({"type": f["type"].replace("_", " "), "detail": f["detail"],
                               "document": f.get("doc_id")})
    data["overrides"] = repo.list_resolution_overrides(db, case.id)
    return data


